cadena = "123456789"

print(cadena[0]) # acceso normal

print(cadena[1:3]) # accede el principio y el anterior numero del final del array

print(cadena[:]) # si no se especifica algun valor sobre alguno de los lados se tiene en cuenta que es el mas grande o mas chico

print(cadena[:-1]) # accede desde el final del array hacia el comienzo del array, el final del array comienza con -1 y va hacia atras
