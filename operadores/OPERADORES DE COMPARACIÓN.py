a = 10
b = 5
print(a == b) # FALSE (compara si "a" es igual a "b")

print(a != b) # TRUE (compara si "a" es desigual a "b")

print(a > b) # TRUE (compara si "a" es mayor a "b")

print(a < b) # FALSE (compara si "a" es menor a "b")

print(a >= 10) # TRUE (compara si "a" es mayor o igual que 10)

print(a <= 10) # TRUE (compara si "a" es menor o igual que 10)
